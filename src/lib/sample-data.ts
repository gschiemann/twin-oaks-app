export type CreateResult =
  | { ok: true; created: ModelCount[]; total: number }
  | { ok: false; reason: "exists" | "failed"; message: string; existing: number };

/** Local noon, the same convention `parseDateInput` uses, so a calendar day
 *  never shifts across timezones. */
function at(year: number, monthIndex: number, day: number): Date {
  return new Date(year, monthIndex, day, 12, 0, 0);
}

function daysAgo(n: number, from: Date = new Date()): Date {
  return at(from.getFullYear(), from.getMonth(), from.getDate() - n);
}

function daysAhead(n: number, from: Date = new Date()): Date {
  return daysAgo(-n, from);
}

/** n months back, clamped to the 28th so every month has the day. */
function monthsAgo(n: number, from: Date = new Date()): Date {
  return at(from.getFullYear(), from.getMonth() - n, Math.min(from.getDate(), 28));
}

/**
 * Which divisions this business actually uses. The owner's books run
 * FARM / TECH / SHARED; a business signed up later usually has just GENERAL,
 * and sample data must not stamp divisions its screens don't show.
 */
function divisionsFor(divisions: Division[]): { farm: string; tech: string; shared: string } {
  const fallback: string = divisions[0] ?? "GENERAL";
  const pick = (d: Division): string => (divisions.includes(d) ? d : fallback);
  return { farm: pick("FARM"), tech: pick("TECH"), shared: pick("SHARED") };
}

