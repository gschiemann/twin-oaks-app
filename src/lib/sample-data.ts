// ───────────────────────────── prisma plumbing ─────────────────────────────
//
// Prisma's delegates are heavily generic; this file only ever needs three
// operations, uniformly, across twenty-one models. The map below references
// the real `prisma.<model>` properties (so a typo is a compile error), and the
// single cast narrows each delegate to those three calls. The safety of this
// file does NOT rest on the cast: every `where` clause is built by the helpers
// below, never by a caller.

type Row = Record<string, unknown>;

type RowDelegate = {
  count(args: { where: Row }): Promise<number>;
  findMany(args: { where: Row; select: Record<string, boolean> }): Promise<Row[]>;
  deleteMany(args: { where: Row }): Promise<{ count: number }>;
};

const DELEGATES = {
  filamentUse: prisma.filamentUse,
  receiptLine: prisma.receiptLine,
  invoiceLine: prisma.invoiceLine,
  payment: prisma.payment,
  animalEvent: prisma.animalEvent,
  maintenanceRecord: prisma.maintenanceRecord,
  receipt: prisma.receipt,
  printJob: prisma.printJob,
  filamentSpool: prisma.filamentSpool,
  livestockSale: prisma.livestockSale,
  animal: prisma.animal,
  invoice: prisma.invoice,
  customer: prisma.customer,
  expense: prisma.expense,
  income: prisma.income,
  mileageLog: prisma.mileageLog,
  asset: prisma.asset,
  vendor: prisma.vendor,
  bankTransaction: prisma.bankTransaction,
  recurringBill: prisma.recurringBill,
  householdExpense: prisma.householdExpense,
  document: prisma.document,
} satisfies Record<ReferrerKey, unknown>;

function delegate(key: ReferrerKey): RowDelegate {
  return DELEGATES[key] as unknown as RowDelegate;
}

/** InvoiceLine has no accountId column of its own — it is scoped through its
 *  invoice. Everything else carries the column. */
function accountScope(scope: AccountScope, accountId: string): Row {
  return scope.kind === "column" ? { accountId } : { [scope.through]: { accountId } };
}

function scopeOf(key: ReferrerKey, accountId: string): Row {
  const spec = MODELS.find((m) => m.key === key);
  return accountScope(spec ? spec.scope : COLUMN, accountId);
}

/** An account id must be a real, non-empty string before any query runs.
 *  A blank one would widen every `where` clause in this file. */
function assertAccount(accountId: string): void {
  if (typeof accountId !== "string" || accountId.trim() === "") {
    throw new Error("sample-data: an account id is required");
  }
}

// ─────────────────────────────── counting ──────────────────────────────────

export type ModelCount = { key: ModelKey; label: string; count: number };

export type DataOverview = {
  /** Per record type, with zeros included so callers can decide what to show. */
  rows: { key: ModelKey; label: string; sample: number; real: number }[];
  sampleTotal: number;
  realTotal: number;
};

/**
 * How many sample rows exist right now, per model. This is the number the UI
 * shows before and after, so the operator is never guessing.
 */
export async function sampleDataCounts(accountId: string): Promise<ModelCount[]> {
  assertAccount(accountId);
  return Promise.all(
    MODELS.map(async (spec) => ({
      key: spec.key,
      label: spec.label,
      count: await delegate(spec.key).count({
        where: { ...accountScope(spec.scope, accountId), id: { startsWith: SAMPLE_ID_PREFIX } },
      }),
    })),
  );
}

/** Total across a set of per-model counts. */
export function totalOf(counts: { count: number }[]): number {
  return counts.reduce((sum, c) => sum + c.count, 0);
}

/**
 * Sample rows AND real rows, side by side, over the same twenty-one record
 * types. (Settings, passkeys, saved documents and tracker items are not
 * business records — sample data never creates them and never counts them.)
 */
export async function dataOverview(accountId: string): Promise<DataOverview> {
  assertAccount(accountId);
  const rows = await Promise.all(
    MODELS.map(async (spec) => {
      const scope = accountScope(spec.scope, accountId);
      const d = delegate(spec.key);
      const [sample, real] = await Promise.all([
        d.count({ where: { ...scope, id: { startsWith: SAMPLE_ID_PREFIX } } }),
        d.count({ where: { ...scope, NOT: { id: { startsWith: SAMPLE_ID_PREFIX } } } }),
      ]);
      return { key: spec.key, label: spec.label, sample, real };
    }),
  );
  return {
    rows,
    sampleTotal: rows.reduce((s, r) => s + r.sample, 0),
    realTotal: rows.reduce((s, r) => s + r.real, 0),
  };
}

// ─────────────────────────────── removal ───────────────────────────────────

export type KeptGroup = { key: ModelKey; label: string; count: number; reasons: string[] };

export type RemovalReport = {
  /** Per model, what was actually deleted (zeros dropped). */
  removed: ModelCount[];
  removedTotal: number;
  /** Sample rows deliberately left alone because real records hang off them. */
  kept: KeptGroup[];
  keptTotal: number;
  /** The operator's own records, counted after the sweep. Never touched. */
  realTotal: number;
};

/** The sample ids of one model, in id order. */
async function sampleIdsOf(spec: ModelSpec, accountId: string): Promise<string[]> {
  const rows = await delegate(spec.key).findMany({
    where: { ...accountScope(spec.scope, accountId), id: { startsWith: SAMPLE_ID_PREFIX } },
    select: { id: true },
  });
  // Re-checked rather than trusted: only ids that really carry the mark.
  return rows.map((r) => r.id).filter(isSampleId);
}

/**
 * Which of these sample rows have one of the OPERATOR'S OWN rows pointing at
 * them. Those are the rows removal must not touch: deleting them would either
 * cascade into a real record, blank a field on one, or leave one pointing at
 * something that no longer exists.
 */
async function blockedBy(
  spec: ModelSpec,
  accountId: string,
  ids: string[],
): Promise<{ blocked: Set<string>; reasons: string[] }> {
  const blocked = new Set<string>();
  const reasons = new Set<string>();
  if (ids.length === 0 || spec.referrers.length === 0) return { blocked, reasons: [] };

  for (const ref of spec.referrers) {
    const rows = await delegate(ref.model).findMany({
      where: {
        ...scopeOf(ref.model, accountId),
        ...(ref.match ?? {}),
        [ref.field]: { in: ids },
        // "Not a sample row" — i.e. one of the operator's own.
        NOT: { id: { startsWith: SAMPLE_ID_PREFIX } },
      },
      select: { [ref.field]: true },
    });
    for (const row of rows) {
      const parentId = row[ref.field];
      if (typeof parentId === "string") {
        blocked.add(parentId);
        reasons.add(ref.reason);
      }
    }
  }
  return { blocked, reasons: [...reasons] };
}

/**
 * ★ THE ONLY DELETE IN THIS FILE. ★
 *
 * The `where` clause is constructed here and cannot be passed in. It always
 * carries the account scope AND an explicit id list, and every id in that list
 * must pass `isSampleId`. An empty list deletes nothing (Prisma's `in: []`
 * matches no rows) rather than everything.
 */
async function deleteSampleRows(spec: ModelSpec, accountId: string, ids: string[]): Promise<number> {
  assertAccount(accountId);
  const safeIds = ids.filter(isSampleId);
  if (safeIds.length === 0) return 0;
  const result = await delegate(spec.key).deleteMany({
    where: { ...accountScope(spec.scope, accountId), id: { in: safeIds } },
  });
  return result.count;
}

/**
 * Deletes exactly and only the sample rows, children before parents, and
 * reports what went. A sample row that one of the operator's own records is
 * attached to is KEPT and reported — this function will leave sample data
 * behind before it will disturb a real record.
 */
export async function removeSampleData(accountId: string): Promise<RemovalReport> {
  assertAccount(accountId);

  const removed: ModelCount[] = [];
  const kept: KeptGroup[] = [];

  for (const spec of MODELS) {
    const ids = await sampleIdsOf(spec, accountId);
    if (ids.length === 0) continue;

    const { blocked, reasons } = await blockedBy(spec, accountId, ids);
    const removable = ids.filter((id) => !blocked.has(id));

    const count = await deleteSampleRows(spec, accountId, removable);
    if (count > 0) removed.push({ key: spec.key, label: spec.label, count });
    if (blocked.size > 0) {
      kept.push({ key: spec.key, label: spec.label, count: blocked.size, reasons });
    }
  }

  // Counted after the sweep, so the number reported to the operator is the
  // truth as it stands, not a number from before.
  const after = await dataOverview(accountId);

  return {
    removed,
    removedTotal: totalOf(removed),
    kept,
    keptTotal: kept.reduce((s, k) => s + k.count, 0),
    realTotal: after.realTotal,
  };
}

