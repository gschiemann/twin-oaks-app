// ═══════════════════════════════════════════════════════════════════════════
// Twin Oaks OS — SAMPLE DATA (FR-003, "safe testing mode")
//
// Practice records so the whole app — receipts, invoices, sheep, print jobs,
// filament, banking, bills — can be exercised end to end, and then removed
// again without ever endangering the real books.
//
// ───────────────────────── THE SAFETY CONTRACT ─────────────────────────────
//
//   NOTHING IN THIS FILE CAN EVER DELETE A ROW THE OPERATOR ENTERED HIMSELF.
//
// That is not a promise made in prose — it is made in the structure:
//
//   1. MARKING. Every row this file creates is given an explicit id that
//      begins with `sample-` (see SAMPLE_ID_PREFIX). Ids are generated by the
//      app, never typed by the operator, never editable from any screen, and
//      never rewritten by an edit. So the mark cannot be scrubbed off a
//      sample row, and cannot be accidentally applied to a real one.
//
//   2. ONE DELETE. `deleteSampleRows` below is the ONLY function in this file
//      that calls `deleteMany`. It builds its own `where` clause — a caller
//      cannot supply one — and that clause always carries BOTH the account
//      scope AND an id filter restricted to ids that passed `isSampleId`.
//      An empty id list matches nothing rather than everything.
//
//   3. NO COLLATERAL DAMAGE. Some sample rows are parents of rows that would
//      cascade-delete with them (an invoice's payments, a spool's filament
//      uses, a ewe's events) or that would be silently detached from them
//      (an expense pinned to a piece of equipment). If the operator has
//      attached one of HIS OWN records to a sample record, that sample record
//      is NOT deleted at all — it is reported as "kept" instead, with the
//      reason. Removal is allowed to leave sample data behind; it is never
//      allowed to touch the operator's data. See REFERRERS below.
//
// WHY THE ID PREFIX, AND WHERE IT COULD FAIL
//
//   Rejected alternatives:
//     • "created after timestamp X" — a clock is not an identity. A restore,
//       an import, a timezone, or the operator entering a real receipt in the
//       same minute all break it, and it silently over-matches.
//     • "description starts with SAMPLE" — free text. The operator is invited
//       to edit these records (that is the point of practice data), and the
//       moment he does, the mark is gone or, worse, lands on a real row he
//       typed the word "sample" into.
//     • a new `isSample` column — not permitted here, and it would need a
//       schema migration on a live database to add one bit of bookkeeping.
//
//   Known failure modes of the id prefix, stated honestly:
//     a) A row whose id was NOT created by this file could in principle start
//        with `sample-`. In practice it cannot: every id in the schema is
//        `@default(cuid())`, and a cuid is always lowercase alphanumeric
//        starting with `c` — it can never contain a hyphen, so it can never
//        collide with this prefix. The only writer of `sample-` ids in the
//        codebase is this file. If a future feature ever starts assigning
//        hand-written ids, it must not use this prefix.
//     b) Restoring a JSON backup that was taken while sample data existed
//        brings the sample rows back — with their ids intact, so they are
//        still exactly removable. This is the desired behaviour, not a bug.
//     c) A sample row EDITED by the operator is still a sample row, and is
//        still removed. The id does not change when a record is edited, which
//        is precisely why it is the mark. If he wants to keep something he
//        built on top of sample data, he must re-enter it (the removal screen
//        says exactly how many rows are about to go, before they go).
//     d) Removal can be incomplete (case 3 above). It can never be too broad.
//
// A NOTE ON THE VISIBLE "(sample)" LABELS IN THE TEXT BELOW: they are for the
// operator's eyes only, so he can tell practice records from his own at a
// glance on every screen. NO code in this file reads them. Deleting is driven
// by the id and nothing else.
// ═══════════════════════════════════════════════════════════════════════════

