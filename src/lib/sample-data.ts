/** The indelible mark. Every sample row's id begins with this. */
export const SAMPLE_ID_PREFIX = "sample-";

/** Cosmetic only — never used to decide what gets deleted. */
const TAG = "(sample)";

export function isSampleId(id: unknown): id is string {
  return typeof id === "string" && id.startsWith(SAMPLE_ID_PREFIX);
}

/** Builds a sample id. Every create below goes through this — there are no
 *  hand-written id literals, so an unmarked row cannot be generated. */
function sid(...parts: string[]): string {
  return SAMPLE_ID_PREFIX + parts.join("-");
}

